const fs = require('fs');
const path = require('path');

const PROJECT_ROOT = path.join(__dirname, '..');
const REPORT_PATH = path.join(PROJECT_ROOT, 'data', 'pricing-update-report.json');
const HEALTH_REPORT_PATH = path.join(PROJECT_ROOT, 'data', 'data-health-report.json');

// Flag a source once this share of its mapped models fail to match a price.
const MISSING_RATIO_THRESHOLD = 0.3;

function collectIssues(report) {
  const issues = [];

  for (const step of report.steps || []) {
    if (step.status === 'failed') {
      issues.push({
        severity: 'error',
        title: `Step "${step.name}" failed`,
        detail: (step.stderr || step.stdout || 'No output captured').slice(0, 1000),
      });
    }
  }

  if (report.validationError) {
    issues.push({
      severity: 'error',
      title: 'Output validation failed',
      detail: report.validationError,
    });
  }

  for (const [sourceName, sourceReport] of Object.entries(report.summary || {})) {
    if (!sourceReport) continue;

    for (const fetchError of sourceReport.fetchErrors || []) {
      issues.push({
        severity: 'warning',
        title: `${sourceName}: fetch failed for "${fetchError.provider}"`,
        detail: fetchError.message,
      });
    }

    const mapped = (sourceReport.matched || 0) + (sourceReport.missing || 0);
    if (mapped > 0 && sourceReport.missing / mapped >= MISSING_RATIO_THRESHOLD) {
      const percent = Math.round((sourceReport.missing / mapped) * 100);
      issues.push({
        severity: 'warning',
        title: `${sourceName}: high unmapped-model rate (${percent}%)`,
        detail: `${sourceReport.missing}/${mapped} models unmapped as of ${sourceReport.fetchedAt || 'unknown time'}`,
      });
    }
  }

  return issues;
}

function toMarkdown(report, issues) {
  const lines = [
    `_Auto-generated by \`scripts/check-data-health.js\` from the pricing update run at ${report.generatedAt}._`,
    '',
  ];

  for (const issue of issues) {
    const emoji = issue.severity === 'error' ? '🔴' : '🟡';
    lines.push(`### ${emoji} ${issue.title}`, '', '```', issue.detail, '```', '');
  }

  return lines.join('\n');
}

function writeGithubOutput(name, value) {
  const outputPath = process.env.GITHUB_OUTPUT;
  if (!outputPath) return;
  fs.appendFileSync(outputPath, `${name}=${value}\n`, 'utf8');
}

function main() {
  if (!fs.existsSync(REPORT_PATH)) {
    console.error(`No pricing update report found at ${REPORT_PATH}`);
    writeGithubOutput('has_issues', 'false');
    return;
  }

  const report = JSON.parse(fs.readFileSync(REPORT_PATH, 'utf8'));
  const issues = collectIssues(report);
  const hasIssues = issues.length > 0;

  const healthReport = {
    generatedAt: new Date().toISOString(),
    sourceReportGeneratedAt: report.generatedAt,
    hasIssues,
    issueCount: issues.length,
    issues,
    markdownBody: hasIssues ? toMarkdown(report, issues) : null,
  };

  fs.mkdirSync(path.dirname(HEALTH_REPORT_PATH), { recursive: true });
  fs.writeFileSync(HEALTH_REPORT_PATH, JSON.stringify(healthReport, null, 2) + '\n', 'utf8');

  console.log(hasIssues ? `Found ${issues.length} data health issue(s):` : 'No data health issues detected.');
  for (const issue of issues) {
    console.log(`  - [${issue.severity}] ${issue.title}`);
  }

  writeGithubOutput('has_issues', String(hasIssues));
}

main();
