const fs = require('fs');
const path = require('path');

const PROJECT_ROOT = path.join(__dirname, '..');
const OPENROUTER_JSON_PATH = path.join(PROJECT_ROOT, 'data', 'openrouter-models.generated.json');
const OUTPUT_JS_PATH = path.join(PROJECT_ROOT, 'js', 'openrouter-free-models.generated.js');
const REPORT_PATH = path.join(PROJECT_ROOT, 'data', 'openrouter-free-models-report.json');

// OpenRouter's free (":free") lineup rotates on their own schedule —
// models get added and retired without notice. Rather than hand-typing
// a snapshot that silently goes stale (see data/openrouter-merge-report.json
// history), this script derives the free list from the same raw fetch
// already used for pricing (data/openrouter-models.generated.json),
// every time the pricing pipeline runs.

function readJson(filePath) {
  return JSON.parse(fs.readFileSync(filePath, 'utf8'));
}

function isFreeModel(model) {
  return model.id.endsWith(':free') && model.inputPrice === 0 && model.outputPrice === 0;
}

function toInternalId(openrouterId) {
  return 'free-or-' + openrouterId
    .replace(/:free$/, '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');
}

function cleanModelName(name, fallbackId) {
  if (!name) return fallbackId;
  return name
    .replace(/^[^:]+:\s*/, '') // strip leading "Provider: "
    .replace(/\s*\(free\)\s*$/i, '') // strip trailing "(free)"
    .trim() || fallbackId;
}

function inferCapabilities(model) {
  const caps = [];
  const params = Array.isArray(model.supportedParameters) ? model.supportedParameters : [];
  const inputModalities = (model.architecture && model.architecture.input_modalities) || [];

  if (inputModalities.includes('image')) caps.push('vision');
  if (params.includes('tools') || params.includes('tool_choice')) caps.push('function-calling');
  if (params.includes('response_format') || params.includes('structured_outputs')) caps.push('json-mode');
  if (params.includes('reasoning') || params.includes('include_reasoning')) caps.push('reasoning');

  return caps;
}

function toFreeModelEntry(model) {
  return {
    id: toInternalId(model.id),
    priceUsdPerMillion: 0,
    modelName: cleanModelName(model.name, model.modelSlug || model.id),
    modelId: model.id,
    provider: 'openrouter',
    apiEndpoint: 'openrouter.ai/api/v1',
    contextWindow: model.contextWindow || null,
    capabilities: inferCapabilities(model),
    rateLimits: 'Shared OpenRouter free-tier limit (account-wide, not per-model)',
    requiresCard: false,
    signup: 'https://openrouter.ai',
    docs: `https://openrouter.ai/${model.id}`,
    note_en: 'Free via OpenRouter. Free-tier availability can change without notice — check docs before relying on it in production.',
    note_id: 'Gratis lewat OpenRouter. Ketersediaan tier gratis bisa berubah sewaktu-waktu — cek dokumentasi sebelum dipakai di produksi.',
    updatedAt: model.updatedAt || null,
  };
}

function generateBrowserFile(entries, report) {
  return `// =============================================================================\n` +
    `// Generated by scripts/build-openrouter-free-models.js\n` +
    `// Source: ${report.source}\n` +
    `// Fetched: ${report.fetchedAt}\n` +
    `// Free models found: ${report.count}\n` +
    `// =============================================================================\n\n` +
    `(function () {\n` +
    `  'use strict';\n\n` +
    `  const OPENROUTER_FREE_MODELS = ${JSON.stringify(entries, null, 2)};\n\n` +
    `  window.OPENROUTER_FREE_MODELS = OPENROUTER_FREE_MODELS;\n` +
    `  window.OPENROUTER_FREE_MODELS_REPORT = ${JSON.stringify(report, null, 2)};\n\n` +
    `  if (Array.isArray(window.FREE_API_MODELS)) {\n` +
    `    window.FREE_API_MODELS.push(...OPENROUTER_FREE_MODELS);\n` +
    `  }\n` +
    `})();\n`;
}

function main() {
  const openrouterData = readJson(OPENROUTER_JSON_PATH);
  const freeModels = (openrouterData.models || []).filter(isFreeModel);
  const entries = freeModels.map(toFreeModelEntry);

  const report = {
    source: openrouterData.source,
    fetchedAt: openrouterData.fetchedAt,
    generatedAt: new Date().toISOString(),
    count: entries.length,
    modelIds: entries.map(entry => entry.modelId),
  };

  fs.writeFileSync(OUTPUT_JS_PATH, generateBrowserFile(entries, report), 'utf8');
  fs.writeFileSync(REPORT_PATH, JSON.stringify(report, null, 2) + '\n', 'utf8');

  console.log(`Generated ${entries.length} free OpenRouter models at ${OUTPUT_JS_PATH}`);
  console.log(`Generated report at ${REPORT_PATH}`);
}

main();
